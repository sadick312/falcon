// npm run docs:settings: writes docs/SETTINGS.md from the menu's own settings data
// (mod-source/src/core/menu/content), so the reference can't drift from the code.
// --check only compares and fails if the file is out of date (used in CI).
import * as esbuild from "esbuild";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join, resolve } from "path";
import { pathToFileURL } from "url";

const root = resolve(import.meta.dirname, "..");
const outFile = join(root, "docs", "SETTINGS.md");
const check = process.argv.includes("--check");

/** Bundles the plain-data settings files and imports them. */
async function loadMenuContent() {
    const dir = mkdtempSync(join(tmpdir(), "falcon-settings-"));
    const bundle = join(dir, "content.mjs");
    try {
        await esbuild.build({
            entryPoints: [join(root, "mod-source", "src", "core", "menu", "content", "index.ts")],
            bundle: true,
            format: "esm",
            platform: "neutral",
            outfile: bundle,
            logLevel: "error"
        });
        return (await import(pathToFileURL(bundle).href)).menuContent;
    } finally {
        rmSync(dir, { recursive: true, force: true });
    }
}

/** Descriptions may hold HTML and template-string indentation; keep plain text on one line. */
function plain(text = "") {
    return text.replace(/<br\s*\/?>/gi, " ").replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
}

function describeValue(item, value) {
    if (item.type === "toggle") return value ? "on" : "off";
    if (item.type === "select") return item.options?.find((option) => String(option.value) === String(value))?.label ?? String(value);
    return String(value);
}

function describeKind(item) {
    if (item.type === "slider" || item.type === "number") {
        const range = typeof item.min === "number" && typeof item.max === "number" ? ` ${item.min}–${item.max}` : "";
        return `${item.type}${range}`;
    }
    return item.type;
}

const SETTING_TYPES = new Set(["toggle", "select", "slider", "number"]);

function renderItems(items, depth, lines) {
    const indent = "  ".repeat(depth);

    for (const item of items) {
        if (item.type === "group") {
            lines.push(`${indent}- **${plain(item.label)}** (group)${item.description ? ` — ${plain(item.description)}` : ""}`);
            renderItems(item.settings ?? [], depth + 1, lines);
            continue;
        }

        if (!SETTING_TYPES.has(item.type) || !item.id) continue;

        const facts = [`\`${item.id}\``, describeKind(item), `default: ${describeValue(item, item.status)}`];
        if (item.neverSave) facts.push("not saved");
        if (item.unchangable) facts.push("locked");
        let line = `${indent}- **${plain(item.label)}** (${facts.join(", ")})`;
        if (item.description) line += ` — ${plain(item.description)}`;
        if (item.type === "select" && item.options?.length) line += ` Options: ${item.options.map((option) => plain(option.label)).join(" / ")}.`;
        lines.push(line);

        if (item.settings?.length) renderItems(item.settings, depth + 1, lines);
    }
}

const TAB_TITLES = {
    combat: "Combat",
    utility: "Utility",
    defense: "Defense",
    visual: "Visual",
    console: "Console",
    configs: "Configs",
    experimentals: "Experimentals"
};

const menuContent = await loadMenuContent();
const lines = [
    "# Menu settings",
    "",
    "<!-- Generated by `npm run docs:settings` from mod-source/src/core/menu/content. Don't edit by hand. -->",
    "",
    "Every setting in the Falcon menu (press **Esc** in game), by tab. Each entry shows the setting's id (what",
    "the code and exported settings files use), its kind, its default and the menu's own description.",
    "Settings nested under another one open from that setting's arrow or gear button.",
    "",
    "The **Favorites** tab lists the settings you starred; **Credits** has no settings.",
    ""
];

for (const [key, title] of Object.entries(TAB_TITLES)) {
    const items = menuContent[key];
    if (!items) continue;
    lines.push(`## ${title}`, "");
    renderItems(items, 0, lines);
    lines.push("");
}

const markdown = lines.join("\n");

if (check) {
    let current = "";
    try {
        current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n");
    } catch { /* missing counts as out of date */ }
    if (current !== markdown) {
        console.error("docs/SETTINGS.md is out of date. Run \"npm run docs:settings\" and commit the result.");
        process.exit(1);
    }
    console.log("docs/SETTINGS.md is up to date.");
} else {
    writeFileSync(outFile, markdown);
    console.log(`Wrote ${outFile}`);
}
